/**
 * Find matching specific products from the curated catalog based on search query
 * @param {string} query
 * @returns {Array} List of specific product objects
 */
export function findCatalogProducts(query) {
  if (!query) return [];
  const normalized = query.toLowerCase().trim();

  let bestMatch = null;
  let highestScore = 0;

  for (const entry of CATALOG) {
    let score = 0;
    for (const kw of entry.keywords) {
      if (normalized.includes(kw.toLowerCase())) {
        score += kw.length;
      }
    }
    if (score > highestScore) {
      highestScore = score;
      bestMatch = entry;
    }
  }

  if (bestMatch && highestScore > 0) {
    return bestMatch.products.map(p => ({ ...p }));
  }

  // Fallback: match by generic keyword tokens
  const tokens = normalized.split(/\s+/);
  for (const entry of CATALOG) {
    const hasAny = tokens.some(t => entry.keywords.some(k => k.includes(t)));
    if (hasAny) {
      return entry.products.slice(0, 2).map(p => ({ ...p }));
    }
  }

  // Default fallback: return first entry products
  return CATALOG[0].products.slice(0, 2).map(p => ({ ...p }));
}
